# CellD: SmallUNet3D modell definíció

class DoubleConv(nn.Module):
    def __init__(self, in_ch, out_ch):
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv3d(in_ch, out_ch, 3, padding=1),
            nn.InstanceNorm3d(out_ch),
            nn.ReLU(inplace=True),
            nn.Conv3d(out_ch, out_ch, 3, padding=1),
            nn.InstanceNorm3d(out_ch),
            nn.ReLU(inplace=True),
        )
    def forward(self, x):
        return self.net(x)

class SmallUNet3D(nn.Module):
    def __init__(self, in_channels=4, out_channels=1, base_ch=8):
        super().__init__()
        self.down1 = DoubleConv(in_channels, base_ch)
        self.pool1 = nn.MaxPool3d(2)

        self.down2 = DoubleConv(base_ch, base_ch*2)
        self.pool2 = nn.MaxPool3d(2)

        self.bottom = DoubleConv(base_ch*2, base_ch*4)

        self.up2 = nn.ConvTranspose3d(base_ch*4, base_ch*2, 2, stride=2)
        self.conv2 = DoubleConv(base_ch*4, base_ch*2)

        self.up1 = nn.ConvTranspose3d(base_ch*2, base_ch, 2, stride=2)
        self.conv1 = DoubleConv(base_ch*2, base_ch)

        self.out_conv = nn.Conv3d(base_ch, out_channels, 1)

    def forward(self, x):
        c1 = self.down1(x); p1 = self.pool1(c1)
        c2 = self.down2(p1); p2 = self.pool2(c2)
        cb = self.bottom(p2)
        u2 = self.up2(cb); c2_cat = torch.cat([u2, c2], dim=1); c2_out = self.conv2(c2_cat)
        u1 = self.up1(c2_out); c1_cat = torch.cat([u1, c1], dim=1); c1_out = self.conv1(c1_cat)
        return self.out_conv(c1_out)

