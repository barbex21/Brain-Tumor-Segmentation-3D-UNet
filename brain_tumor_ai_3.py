class UPennGBMDataset(Dataset):
    def __init__(self, csv_path, target_size=(128,128,128)):
        self.meta = np.genfromtxt(csv_path, delimiter=',', dtype=str, skip_header=1)
        self.target_size = target_size

    def __len__(self):
        return len(self.meta)

    def __getitem__(self, idx):
        row = self.meta[idx]
        flair_path = row[1]
        t1_path    = row[2]
        t1ce_path  = row[3]
        t2_path    = row[4]
        mask_path  = row[5]

        try:
            flair = nib.load(flair_path).get_fdata().astype(np.float32)
            t1    = nib.load(t1_path).get_fdata().astype(np.float32)
            t1ce  = nib.load(t1ce_path).get_fdata().astype(np.float32)
            t2    = nib.load(t2_path).get_fdata().astype(np.float32)
            mask  = nib.load(mask_path).get_fdata().astype(np.float32)
        except FileNotFoundError:
            return self.__getitem__((idx + 1) % len(self))

        vol = np.stack([flair, t1, t1ce, t2], axis=0)
        D,H,W = vol.shape[1:]
        td,th,tw = self.target_size
        sd = max((D-td)//2, 0); sh = max((H-th)//2, 0); sw = max((W-tw)//2, 0)
        ed = sd + td; eh = sh + th; ew = sw + tw

        vol_c  = vol[:, sd:ed, sh:eh, sw:ew]
        mask_c = mask[sd:ed, sh:eh, sw:ew]

        # --- ITT binarizáljuk a maszkot: bármi >0 tumor ---
        mask_c = (mask_c > 0).astype(np.float32)
        # -----------------------------------------------

        vol_c = (vol_c - vol_c.mean()) / (vol_c.std() + 1e-8)

        x = torch.from_numpy(vol_c).float()
        y = torch.from_numpy(mask_c).float().unsqueeze(0)
        return x, y

