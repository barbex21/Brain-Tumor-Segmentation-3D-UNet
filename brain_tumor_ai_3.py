import numpy as np

def dice_iou_single(pred_bin, target_bin, eps=1e-6):
    # pred_bin, target_bin: [1,1,D,H,W], 0/1
    inter = (pred_bin * target_bin).sum().item()
    pred_sum = pred_bin.sum().item()
    targ_sum = target_bin.sum().item()
    union = pred_sum + targ_sum - inter

    dice = (2 * inter + eps) / (pred_sum + targ_sum + eps)
    iou  = (inter + eps) / (union + eps)
    return dice, iou

